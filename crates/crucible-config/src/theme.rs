//! The `theme` block's data and the pure per-terminal fragment renderer.
//!
//! A [`ThemeConfig`] is rendered by [`render`] into the native syntax of one [`ThemeTarget`]
//! (foot.ini, crucible-term KDL, X resources for urxvt, ghostty `key = value`), emitting only the
//! keys the theme sets. [`theme_dir_from`] resolves where the compositor writes the fragments;
//! the file I/O itself lives at the compositor/CLI edge.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use crate::model::{Named, Rgb};

/// A non-negative decimal kept to three places (`thousandths / 1000`), so the config stays `Eq`.
/// Displays without trailing zeros: `11`, `11.5`, `0.875`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Milli(pub u32);

impl Milli {
    /// `value` rounded to three decimal places; `None` when negative, not finite or too large.
    #[must_use]
    pub fn from_f64(value: f64) -> Option<Self> {
        let scaled = (value * 1000.0).round();
        if !scaled.is_finite() || scaled < 0.0 || scaled > f64::from(u32::MAX) {
            return None;
        }
        #[allow(clippy::cast_possible_truncation, clippy::cast_sign_loss)]
        Some(Self(scaled as u32))
    }
}

impl std::fmt::Display for Milli {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        let (whole, frac) = (self.0 / 1000, self.0 % 1000);
        if frac == 0 {
            return write!(f, "{whole}");
        }
        let digits = format!("{frac:03}");
        write!(f, "{whole}.{}", digits.trim_end_matches('0'))
    }
}

/// The `font "<family>" size=(pt)N` child of `theme`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ThemeFont {
    /// The font family.
    pub family: String,
    /// The size in points, when given.
    pub size: Option<Milli>,
}

/// The `theme { … }` block: one font and colour set rendered for every supported terminal.
/// Every field is optional; only what is set is emitted.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct ThemeConfig {
    /// Font family and size.
    pub font: Option<ThemeFont>,
    /// Default foreground colour.
    pub foreground: Option<Rgb>,
    /// Default background colour.
    pub background: Option<Rgb>,
    /// Cursor colour.
    pub cursor: Option<Rgb>,
    /// Background opacity, `0..=1000` thousandths (`alpha 0.9` is `Milli(900)`).
    pub alpha: Option<Milli>,
    /// ANSI palette entries 0-15.
    pub palette: [Option<Rgb>; 16],
}

/// A terminal a theme fragment is rendered for.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ThemeTarget {
    /// foot (`foot.ini`, included with `include=`).
    Foot,
    /// crucible-term (`cterm.kdl`, included with `include`).
    Cterm,
    /// urxvt (`urxvt.Xresources`, merged by CDE with `xrdb -merge`).
    Urxvt,
    /// ghostty (`ghostty.conf`, passed by CDE as `--config-file=`).
    Ghostty,
}

impl Named for ThemeTarget {
    const NAMES: &'static [(Self, &'static str)] = &[
        (Self::Foot, "foot"),
        (Self::Cterm, "cterm"),
        (Self::Urxvt, "urxvt"),
        (Self::Ghostty, "ghostty"),
    ];
}

impl ThemeTarget {
    /// Every target, in file-writing order.
    pub const ALL: [Self; 4] = [Self::Foot, Self::Cterm, Self::Urxvt, Self::Ghostty];

    /// The fragment's file name inside the theme directory.
    #[must_use]
    pub fn file_name(self) -> &'static str {
        match self {
            Self::Foot => "foot.ini",
            Self::Cterm => "cterm.kdl",
            Self::Urxvt => "urxvt.Xresources",
            Self::Ghostty => "ghostty.conf",
        }
    }
}

/// foot's default background, the cursor text colour when the theme sets no `background`
/// (foot's `cursor=` takes the text and the cursor colour together).
const FOOT_DEFAULT_BACKGROUND: Rgb = Rgb(0x00, 0x2b, 0x36);

fn bare(c: Rgb) -> String {
    format!("{:02x}{:02x}{:02x}", c.0, c.1, c.2)
}

fn hash(c: Rgb) -> String {
    format!("#{}", bare(c))
}

/// Renders `theme` in `target`'s native syntax. **Pure.** An empty theme renders the header only.
#[must_use]
pub fn render(theme: &ThemeConfig, target: ThemeTarget) -> String {
    match target {
        ThemeTarget::Foot => render_foot(theme),
        ThemeTarget::Cterm => render_cterm(theme),
        ThemeTarget::Urxvt => render_urxvt(theme),
        ThemeTarget::Ghostty => render_ghostty(theme),
    }
}

const GENERATED: &str = "Generated by CDE from the `theme` block of cde/config.kdl; do not edit.";

fn render_foot(t: &ThemeConfig) -> String {
    let mut s = format!("# {GENERATED}\n");
    if let Some(font) = &t.font {
        s.push_str("[main]\n");
        match font.size {
            Some(size) => writeln!(s, "font={}:size={size}", font.family),
            None => writeln!(s, "font={}", font.family),
        }
        .ok();
    }
    let mut colors = String::new();
    if let Some(c) = t.foreground {
        writeln!(colors, "foreground={}", bare(c)).ok();
    }
    if let Some(c) = t.background {
        writeln!(colors, "background={}", bare(c)).ok();
    }
    if let Some(c) = t.cursor {
        let text = t.background.unwrap_or(FOOT_DEFAULT_BACKGROUND);
        writeln!(colors, "cursor={} {}", bare(text), bare(c)).ok();
    }
    if let Some(a) = t.alpha {
        writeln!(colors, "alpha={a}").ok();
    }
    for (i, c) in t.palette.iter().enumerate() {
        if let Some(c) = c {
            let (bank, n) = if i < 8 {
                ("regular", i)
            } else {
                ("bright", i - 8)
            };
            writeln!(colors, "{bank}{n}={}", bare(*c)).ok();
        }
    }
    if !colors.is_empty() {
        s.push_str("[colors-dark]\n");
        s.push_str(&colors);
    }
    s
}

fn kdl_string(s: &str) -> String {
    let mut out = String::from("\"");
    for ch in s.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            _ => out.push(ch),
        }
    }
    out.push('"');
    out
}

fn render_cterm(t: &ThemeConfig) -> String {
    let mut s = format!("// {GENERATED}\n");
    if let Some(font) = &t.font {
        match font.size {
            Some(size) => writeln!(s, "font {} size={size}", kdl_string(&font.family)),
            None => writeln!(s, "font {}", kdl_string(&font.family)),
        }
        .ok();
    }
    let mut colors = String::new();
    for (key, c) in [
        ("foreground", t.foreground),
        ("background", t.background),
        ("cursor", t.cursor),
    ] {
        if let Some(c) = c {
            writeln!(colors, "    {key} \"{}\"", hash(c)).ok();
        }
    }
    if let Some(a) = t.alpha {
        writeln!(colors, "    alpha {}", float_literal(a)).ok();
    }
    for (i, c) in t.palette.iter().enumerate() {
        if let Some(c) = c {
            writeln!(colors, "    palette {i} \"{}\"", hash(*c)).ok();
        }
    }
    if !colors.is_empty() {
        s.push_str("colors {\n");
        s.push_str(&colors);
        s.push_str("}\n");
    }
    s
}

/// A KDL float literal (`1.0`, `0.9`), so the value reads as a number with a decimal point.
fn float_literal(m: Milli) -> String {
    let s = m.to_string();
    if s.contains('.') { s } else { format!("{s}.0") }
}

fn render_urxvt(t: &ThemeConfig) -> String {
    let mut s = format!("! {GENERATED}\n");
    if let Some(font) = &t.font {
        match font.size {
            Some(size) => writeln!(s, "URxvt.font: xft:{}:size={size}", font.family),
            None => writeln!(s, "URxvt.font: xft:{}", font.family),
        }
        .ok();
    }
    if let Some(c) = t.foreground {
        writeln!(s, "URxvt*foreground: {}", hash(c)).ok();
    }
    if let Some(c) = t.background {
        match t.alpha {
            // urxvt's `[NN]` prefix is a percentage; it takes effect only with `URxvt.depth: 32`,
            // which stays in the user's own resources.
            Some(a) if a.0 < 1000 => {
                writeln!(s, "URxvt*background: [{}]{}", (a.0 + 5) / 10, hash(c))
            }
            _ => writeln!(s, "URxvt*background: {}", hash(c)),
        }
        .ok();
    }
    if let Some(c) = t.cursor {
        writeln!(s, "URxvt*cursorColor: {}", hash(c)).ok();
    }
    for (i, c) in t.palette.iter().enumerate() {
        if let Some(c) = c {
            writeln!(s, "*color{i}: {}", hash(*c)).ok();
        }
    }
    s
}

fn render_ghostty(t: &ThemeConfig) -> String {
    let mut s = format!("# {GENERATED}\n");
    if let Some(font) = &t.font {
        writeln!(s, "font-family = {}", font.family).ok();
        if let Some(size) = font.size {
            writeln!(s, "font-size = {size}").ok();
        }
    }
    for (key, c) in [
        ("foreground", t.foreground),
        ("background", t.background),
        ("cursor-color", t.cursor),
    ] {
        if let Some(c) = c {
            writeln!(s, "{key} = {}", hash(c)).ok();
        }
    }
    if let Some(a) = t.alpha {
        writeln!(s, "background-opacity = {a}").ok();
    }
    for (i, c) in t.palette.iter().enumerate() {
        if let Some(c) = c {
            writeln!(s, "palette = {i}={}", hash(*c)).ok();
        }
    }
    s
}

/// The fragment directory from the two environment values (`None` or empty = unset):
/// `$XDG_CONFIG_HOME/cde/terminal-theme`, else `$HOME/.config/cde/terminal-theme`. **Pure.**
#[must_use]
pub fn theme_dir_from(xdg_config_home: Option<&str>, home: Option<&str>) -> Option<PathBuf> {
    crate::config_path_from(xdg_config_home, home)
        .and_then(|p| p.parent().map(|cde| cde.join("terminal-theme")))
}

/// [`theme_dir_from`] the process environment.
#[must_use]
pub fn theme_dir() -> Option<PathBuf> {
    theme_dir_from(
        std::env::var("XDG_CONFIG_HOME").ok().as_deref(),
        std::env::var("HOME").ok().as_deref(),
    )
}

/// The extra spawn arguments a theme adds for terminal `program`: with a theme and a fragment
/// `dir`, `--config-file=<dir>/ghostty.conf` for a program whose basename is `ghostty` or
/// `ghostty-cde`; nothing otherwise. **Pure.**
#[must_use]
pub fn theme_spawn_args(
    theme: Option<&ThemeConfig>,
    program: &str,
    dir: Option<&Path>,
) -> Vec<String> {
    let basename = Path::new(program)
        .file_name()
        .and_then(|b| b.to_str())
        .unwrap_or(program);
    match (theme, dir) {
        (Some(_), Some(dir)) if matches!(basename, "ghostty" | "ghostty-cde") => vec![format!(
            "--config-file={}",
            dir.join(ThemeTarget::Ghostty.file_name()).display()
        )],
        _ => Vec::new(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn full() -> ThemeConfig {
        let mut palette = [None; 16];
        palette[0] = Some(Rgb(0x24, 0x24, 0x24));
        palette[1] = Some(Rgb(0xf6, 0x2b, 0x5a));
        palette[15] = Some(Rgb(0xff, 0xff, 0xff));
        ThemeConfig {
            font: Some(ThemeFont {
                family: "JetBrains Mono".into(),
                size: Some(Milli(11_500)),
            }),
            foreground: Some(Rgb(0xdc, 0xdc, 0xcc)),
            background: Some(Rgb(0x11, 0x11, 0x11)),
            cursor: Some(Rgb(0xff, 0x00, 0x80)),
            alpha: Some(Milli(900)),
            palette,
        }
    }

    #[test]
    fn milli_displays_without_trailing_zeros() {
        assert_eq!(Milli(11_000).to_string(), "11");
        assert_eq!(Milli(11_500).to_string(), "11.5");
        assert_eq!(Milli(875).to_string(), "0.875");
        assert_eq!(Milli(0).to_string(), "0");
        assert_eq!(Milli::from_f64(0.9), Some(Milli(900)));
        assert_eq!(Milli::from_f64(-0.1), None);
    }

    #[test]
    fn foot_golden() {
        assert_eq!(
            render(&full(), ThemeTarget::Foot),
            format!(
                "# {GENERATED}\n[main]\nfont=JetBrains Mono:size=11.5\n[colors-dark]\n\
                 foreground=dcdccc\nbackground=111111\ncursor=111111 ff0080\nalpha=0.9\n\
                 regular0=242424\nregular1=f62b5a\nbright7=ffffff\n"
            )
        );
    }

    #[test]
    fn cterm_golden() {
        assert_eq!(
            render(&full(), ThemeTarget::Cterm),
            format!(
                "// {GENERATED}\nfont \"JetBrains Mono\" size=11.5\ncolors {{\n    \
                 foreground \"#dcdccc\"\n    background \"#111111\"\n    cursor \"#ff0080\"\n    \
                 alpha 0.9\n    palette 0 \"#242424\"\n    palette 1 \"#f62b5a\"\n    \
                 palette 15 \"#ffffff\"\n}}\n"
            )
        );
    }

    #[test]
    fn urxvt_golden() {
        assert_eq!(
            render(&full(), ThemeTarget::Urxvt),
            format!(
                "! {GENERATED}\nURxvt.font: xft:JetBrains Mono:size=11.5\n\
                 URxvt*foreground: #dcdccc\nURxvt*background: [90]#111111\n\
                 URxvt*cursorColor: #ff0080\n*color0: #242424\n*color1: #f62b5a\n\
                 *color15: #ffffff\n"
            )
        );
    }

    #[test]
    fn ghostty_golden() {
        assert_eq!(
            render(&full(), ThemeTarget::Ghostty),
            format!(
                "# {GENERATED}\nfont-family = JetBrains Mono\nfont-size = 11.5\n\
                 foreground = #dcdccc\nbackground = #111111\ncursor-color = #ff0080\n\
                 background-opacity = 0.9\npalette = 0=#242424\npalette = 1=#f62b5a\n\
                 palette = 15=#ffffff\n"
            )
        );
    }

    #[test]
    fn partial_theme_emits_only_what_is_set() {
        let t = ThemeConfig {
            cursor: Some(Rgb(1, 2, 3)),
            alpha: Some(Milli(1000)),
            ..ThemeConfig::default()
        };
        assert_eq!(
            render(&t, ThemeTarget::Foot),
            format!("# {GENERATED}\n[colors-dark]\ncursor=002b36 010203\nalpha=1\n")
        );
        assert_eq!(
            render(&t, ThemeTarget::Cterm),
            format!("// {GENERATED}\ncolors {{\n    cursor \"#010203\"\n    alpha 1.0\n}}\n")
        );
        // No background: urxvt cannot express alpha alone; opaque alpha never adds `[NN]`.
        assert_eq!(
            render(&t, ThemeTarget::Urxvt),
            format!("! {GENERATED}\nURxvt*cursorColor: #010203\n")
        );
        let t = ThemeConfig {
            background: Some(Rgb(0, 0, 0)),
            alpha: Some(Milli(1000)),
            font: Some(ThemeFont {
                family: "Mono".into(),
                size: None,
            }),
            ..ThemeConfig::default()
        };
        assert_eq!(
            render(&t, ThemeTarget::Urxvt),
            format!("! {GENERATED}\nURxvt.font: xft:Mono\nURxvt*background: #000000\n")
        );
        assert_eq!(
            render(&t, ThemeTarget::Ghostty),
            format!(
                "# {GENERATED}\nfont-family = Mono\nbackground = #000000\nbackground-opacity = 1\n"
            )
        );
        assert_eq!(
            render(&ThemeConfig::default(), ThemeTarget::Foot),
            format!("# {GENERATED}\n")
        );
    }

    #[test]
    fn urxvt_alpha_percentage_rounds() {
        let t = |a| ThemeConfig {
            background: Some(Rgb(0, 0, 0)),
            alpha: Some(Milli(a)),
            ..ThemeConfig::default()
        };
        assert!(render(&t(875), ThemeTarget::Urxvt).contains("[88]#000000"));
        assert!(render(&t(874), ThemeTarget::Urxvt).contains("[87]#000000"));
        assert!(render(&t(0), ThemeTarget::Urxvt).contains("[0]#000000"));
    }

    #[test]
    fn theme_dir_prefers_xdg_then_home() {
        assert_eq!(
            theme_dir_from(Some("/x"), Some("/h")),
            Some(PathBuf::from("/x/cde/terminal-theme"))
        );
        assert_eq!(
            theme_dir_from(Some(""), Some("/h")),
            Some(PathBuf::from("/h/.config/cde/terminal-theme"))
        );
        assert_eq!(theme_dir_from(None, None), None);
    }

    #[test]
    fn ghostty_spawns_get_the_config_file_only_with_a_theme() {
        let t = ThemeConfig::default();
        let dir = Path::new("/c/cde/terminal-theme");
        let want = vec!["--config-file=/c/cde/terminal-theme/ghostty.conf".to_string()];
        assert_eq!(theme_spawn_args(Some(&t), "ghostty", Some(dir)), want);
        assert_eq!(
            theme_spawn_args(Some(&t), "/opt/bin/ghostty-cde", Some(dir)),
            want
        );
        assert!(theme_spawn_args(None, "ghostty", Some(dir)).is_empty());
        assert!(theme_spawn_args(Some(&t), "ghostty", None).is_empty());
        assert!(theme_spawn_args(Some(&t), "foot", Some(dir)).is_empty());
    }
}
